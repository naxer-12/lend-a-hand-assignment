"""
[Q2: Idempotency in State Payment/Scheme APIs]
Disbursement Payment Controller
-------------------------------
Guarantees strict at-most-once execution for state Direct Benefit Transfers (DBT).
Enforces:
1. Mandatory `Idempotency-Key` HTTP Header.
2. Distributed Redis lock acquisition with atomic NX / in-memory concurrency guard.
3. 409 Conflict if duplicate request arrives while earlier attempt is in flight.
4. Deterministic response replay with `Idempotent-Replay: true` header without double-crediting.
5. Secondary defense via PostgreSQL/SQLite UNIQUE constraint on `disbursements.idempotency_key`.
"""

import uuid
from datetime import datetime, timezone
from decimal import Decimal
from fastapi import APIRouter, Depends, Header, Request, Response, status, HTTPException
from sqlalchemy.orm import Session
from app.database import get_db
from app.models.disbursement import Disbursement
from app.models.student import Student
from app.schemas.disbursement import DisbursementCreate, DisbursementResponse
from app.schemas.problem_detail import ProblemDetail
from app.services.idempotency import idempotency_service
from app.services.audit_service import audit_service
from app.exceptions.handlers import APIProblemException

router = APIRouter(prefix="/disbursements", tags=["Disbursements"])


@router.post(
    "",
    response_model=DisbursementResponse,
    status_code=status.HTTP_201_CREATED,
    responses={
        400: {"model": ProblemDetail, "description": "Missing Idempotency-Key header or invalid data"},
        404: {"model": ProblemDetail, "description": "Referenced student does not exist"},
        409: {"model": ProblemDetail, "description": "Concurrent transaction currently processing"},
    }
)
def process_disbursement(
    disbursement_in: DisbursementCreate,
    request: Request,
    response: Response,
    idempotency_key: str = Header(
        ...,
        alias="Idempotency-Key",
        description="Unique UUID or transaction token generated by client to guarantee idempotent retry."
    ),
    db: Session = Depends(get_db)
):
    """
    [Q2: Idempotent Payment/Disbursement Execution]
    Executes financial scholarship credit to student beneficiary.
    If the caller retries with the same `Idempotency-Key`, returns the cached result
    with header `Idempotent-Replay: true` without invoking the payment engine again.
    """
    clean_key = idempotency_key.strip()
    if not clean_key or len(clean_key) < 8:
        raise APIProblemException(
            status_code=status.HTTP_400_BAD_REQUEST,
            title="Invalid Idempotency Key",
            detail="Header 'Idempotency-Key' must be a valid non-empty unique string (e.g. UUID v4).",
            problem_type="https://evidya.gujarat.gov.in/errors/invalid-idempotency-key"
        )

    # 1. Step 1: Check Idempotency Store (Redis or In-Memory Guard)
    lock_status, cached_result = idempotency_service.acquire_or_check(clean_key, lock_ttl=60)

    # Scenario A: Previous request completed successfully -> Return Idempotent Replay
    if lock_status == "COMPLETED" and cached_result:
        cached_status_code, cached_payload = cached_result
        response.status_code = status.HTTP_200_OK
        response.headers["Idempotent-Replay"] = "true"
        cached_payload["is_idempotent_replay"] = True
        return cached_payload

    # Scenario B: Another concurrent request with this key is executing -> Reject race condition
    if lock_status == "PROCESSING":
        raise APIProblemException(
            status_code=status.HTTP_409_CONFLICT,
            title="Idempotent Transaction In Progress",
            detail="A disbursement request with this Idempotency-Key is currently being processed. Please await completion.",
            problem_type="https://evidya.gujarat.gov.in/errors/idempotency-in-progress"
        )

    # Scenario C: Lock acquired -> Proceed with authoritative financial transaction execution
    try:
        # Check student exists
        student = db.query(Student).filter(Student.id == disbursement_in.student_id).first()
        if not student:
            idempotency_service.release(clean_key)
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"Beneficiary Student ID {disbursement_in.student_id} not found."
            )

        # Database Secondary Defense: Check if DB already has record (e.g. if Redis key expired)
        existing_db_disb = db.query(Disbursement).filter(Disbursement.idempotency_key == clean_key).first()
        if existing_db_disb:
            result_payload = {
                "disbursement_reference": existing_db_disb.disbursement_reference,
                "idempotency_key": existing_db_disb.idempotency_key,
                "student_id": existing_db_disb.student_id,
                "scheme_code": existing_db_disb.scheme_code,
                "amount": float(existing_db_disb.amount),
                "status": existing_db_disb.status,
                "payment_gateway_txn_id": existing_db_disb.payment_gateway_txn_id,
                "executed_at": existing_db_disb.executed_at.isoformat(),
                "is_idempotent_replay": True
            }
            # Cache in Redis for fast future replays
            idempotency_service.complete(clean_key, status.HTTP_200_OK, result_payload)
            response.headers["Idempotent-Replay"] = "true"
            return result_payload

        # Execute Disbursement Simulation (Direct Benefit Transfer via Treasury Gateway)
        disbursement_ref = f"DSB-GJ-{datetime.now(timezone.utc).year}-{uuid.uuid4().hex[:10].upper()}"
        gateway_txn_id = f"PFMS-TXN-{uuid.uuid4().hex[:12].upper()}"
        now = datetime.now(timezone.utc)

        new_disbursement = Disbursement(
            disbursement_reference=disbursement_ref,
            idempotency_key=clean_key,
            student_id=disbursement_in.student_id,
            scheme_code=disbursement_in.scheme_code,
            amount=disbursement_in.amount,
            status="SUCCESS",
            payment_gateway_txn_id=gateway_txn_id,
            executed_at=now
        )

        db.add(new_disbursement)
        db.commit()
        db.refresh(new_disbursement)

        # Prepare response payload
        result_payload = {
            "disbursement_reference": new_disbursement.disbursement_reference,
            "idempotency_key": clean_key,
            "student_id": new_disbursement.student_id,
            "scheme_code": new_disbursement.scheme_code,
            "amount": float(new_disbursement.amount),
            "status": new_disbursement.status,
            "payment_gateway_txn_id": new_disbursement.payment_gateway_txn_id,
            "executed_at": new_disbursement.executed_at.isoformat(),
            "is_idempotent_replay": False
        }

        # Commit final payload into idempotency store for deterministic replay
        idempotency_service.complete(clean_key, status.HTTP_201_CREATED, result_payload)

        # Audit Logging [Q11]
        client_ip = request.client.host if request.client else "127.0.0.1"
        audit_service.record_action(
            db=db,
            actor_id="DBT_DISBURSEMENT_GATEWAY",
            actor_role="FINANCIAL_SERVICE",
            action="DISBURSE_SCHOLARSHIP_FUNDS",
            resource_type="DISBURSEMENT",
            resource_id=str(new_disbursement.id),
            client_ip=client_ip,
            details={
                "reference": disbursement_ref,
                "amount": float(disbursement_in.amount),
                "student_id": disbursement_in.student_id,
                "scheme": disbursement_in.scheme_code
            }
        )

        response.status_code = status.HTTP_201_CREATED
        return result_payload

    except Exception as exc:
        # In case of unhandled error, unlock idempotency key so retry is not blocked indefinitely
        idempotency_service.release(clean_key)
        raise exc
