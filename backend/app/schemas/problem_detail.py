"""
[Q1: API Development & Error Handling]
RFC 7807 Problem Details Schema
-------------------------------
Standardized error format (RFC 7807: Problem Details for HTTP APIs).
Ensures predictable, machine-readable errors across all portal endpoints.
Media Type: application/problem+json
"""

from typing import Optional, List, Dict, Any
from datetime import datetime, timezone
from pydantic import BaseModel, Field, ConfigDict


class InvalidParameter(BaseModel):
    name: str = Field(..., description="Field path or parameter name that failed validation")
    reason: str = Field(..., description="Explanation of why this parameter was rejected")


class ProblemDetail(BaseModel):
    model_config = ConfigDict(
        json_schema_extra={
            "example": {
                "type": "https://evidya.gujarat.gov.in/errors/validation-error",
                "title": "Unprocessable Entity",
                "status": 422,
                "detail": "Field 'family_income' must be a positive number.",
                "instance": "/api/v1/students",
                "timestamp": "2026-09-30T10:00:00Z",
                "invalid_params": [
                    {"name": "family_income", "reason": "Input should be greater than 0"}
                ]
            }
        }
    )

    type: str = Field(
        ...,
        description="URI reference that identifies the problem type",
        examples=["https://evidya.gujarat.gov.in/errors/validation-error"]
    )
    title: str = Field(
        ...,
        description="Short, human-readable summary of the problem type",
        examples=["Request Validation Failed"]
    )
    status: int = Field(
        ...,
        description="The HTTP status code generated by the origin server",
        examples=[422]
    )
    detail: str = Field(
        ...,
        description="Human-readable explanation specific to this occurrence of the problem",
        examples=["One or more submitted fields failed validation checks."]
    )
    instance: str = Field(
        ...,
        description="URI reference that identifies the specific occurrence of the problem",
        examples=["/api/v1/students"]
    )
    timestamp: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="UTC ISO-8601 timestamp when the error occurred"
    )
    invalid_params: Optional[List[InvalidParameter]] = Field(
        None,
        description="Detailed list of specific fields that violated validation constraints"
    )
    extra_context: Optional[Dict[str, Any]] = Field(
        None,
        description="Optional debugging context (only in non-production environments)"
    )
